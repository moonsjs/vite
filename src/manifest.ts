import { findLayouts, routeKeyFromFile, type ApiRouteDefinition, type RouteDefinition } from "@moonsjs/core";
import { relative, sep } from "node:path";

export interface ClientManifestEntry {
  page: string;
  layouts: string[];
}

/** Key manifest untuk halaman kustom `_404` dan `_error` (§11.2). */
export const NOT_FOUND_ROUTE_KEY = "__moons/404";
export const ERROR_ROUTE_KEY = "__moons/error";

/**
 * Manifest route untuk client (PRD §8.2): key = key route file
 * (routeKeyFromFile), nilai = page + layout chain dari root ke leaf.
 */
export function buildClientManifest(
  routes: RouteDefinition[],
  routesDir: string,
): Record<string, ClientManifestEntry> {
  const manifest: Record<string, ClientManifestEntry> = {};
  for (const route of routes) {
    if (route.kind !== "page") {
      continue;
    }
    const key = routeKeyFromFile(routesDir, route.file);
    manifest[key] = {
      page: key,
      layouts: findLayouts(route, routes).map((layout) => routeKeyFromFile(routesDir, layout.file)),
    };
  }

  const notFound = routes.find((route) => route.kind === "404");
  if (notFound !== undefined) {
    manifest[NOT_FOUND_ROUTE_KEY] = { page: routeKeyFromFile(routesDir, notFound.file), layouts: [] };
  }
  const errorRoute = routes.find((route) => route.kind === "error");
  if (errorRoute !== undefined) {
    manifest[ERROR_ROUTE_KEY] = { page: routeKeyFromFile(routesDir, errorRoute.file), layouts: [] };
  }
  // D.3: semua boundary `_error` (termasuk bersarang) ikut manifest — payload
  // memakai key file boundary yang dipilih runtime.
  for (const route of routes) {
    if (route.kind !== "error") {
      continue;
    }
    const key = routeKeyFromFile(routesDir, route.file);
    manifest[key] = { page: key, layouts: [] };
  }

  return manifest;
}

/** `virtual:moons/api` (Addendum D.1 + D.3): tabel API + middleware + peta import(). */
export function renderApiModule(
  apiRoutes: ApiRouteDefinition[],
  apiMiddlewares: ReadonlyArray<{ file: string; dir: string }>,
  projectRoot: string,
): string {
  const loadEntries = apiRoutes
    .map(
      (route) =>
        `  ${JSON.stringify(route.path)}: () => import(${JSON.stringify(rootSpecifier(projectRoot, route.file))}),`,
    )
    .join("\n");
  const middlewareEntries = apiMiddlewares
    .map(
      (middleware) =>
        `  ${JSON.stringify(middleware.file)}: () => import(${JSON.stringify(rootSpecifier(projectRoot, middleware.file))}),`,
    )
    .join("\n");
  return [
    "// Generated by @moons. Do not edit manually.",
    `export const apiRoutes = ${JSON.stringify(apiRoutes, null, 2)};`,
    `export const apiMiddlewares = ${JSON.stringify(apiMiddlewares, null, 2)};`,
    "export const loadApi = {",
    loadEntries,
    "};",
    "export const loadApiMiddleware = {",
    middlewareEntries,
    "};",
    "",
  ].join("\n");
}

/**
 * Isi `virtual:moons/routes`: daftar RouteDefinition, manifest client, dan
 * peta import() dinamis per file route (specifier root-relative).
 */
export function renderRoutesModule(
  routes: RouteDefinition[],
  routesDir: string,
  projectRoot: string,
): string {
  const manifest = buildClientManifest(routes, routesDir);

  const loadEntries = routes.map((route) => {
    const key = routeKeyFromFile(routesDir, route.file);
    return `  ${JSON.stringify(key)}: () => import(${JSON.stringify(rootSpecifier(projectRoot, route.file))}),`;
  });

  return [
    "// Generated by @moons. Do not edit manually.",
    `export const routes = ${JSON.stringify(routes, null, 2)};`,
    "",
    `export const clientManifest = ${JSON.stringify(manifest, null, 2)};`,
    "",
    "export const loadRoute = {",
    ...loadEntries,
    "};",
    "",
  ].join("\n");
}

/** Path file absolut project → specifier root-relative yang bisa di-resolve Vite. */
export function rootSpecifier(projectRoot: string, file: string): string {
  let rel = relative(projectRoot, file);
  rel = sep === "/" ? rel : rel.split(sep).join("/");
  return rel.startsWith("/") ? rel : `/${rel}`;
}
